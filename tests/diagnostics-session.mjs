import assert from 'node:assert/strict';
import { build } from 'esbuild';
const built = await build({ entryPoints: ['server/diagnostics-session.ts'], bundle: true, format: 'esm', platform: 'node', write: false });
const { createDiagnosticsSession, diagnosticsTtl } = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString('base64')}`);
const secret = 'a'.repeat(64), scope = { sessionId: 'trusted', connectionGeneration: 7 };
const operationId = '019a4a10-0000-7000-8000-000000000001';
const timing = { operationId, durationMs: 12, payload: secret };
assert.equal(diagnosticsTtl({}), 0);
assert.equal(diagnosticsTtl({ FIGMA_MCP_DIAGNOSTICS_TTL_MS: '300000' }), 300000);
for (const value of ['-1', '0', '300001', '1e3', secret]) assert.equal(diagnosticsTtl({ FIGMA_MCP_DIAGNOSTICS_TTL_MS: value }), 0);
const log = createDiagnosticsSession(scope, secret, { FIGMA_MCP_DIAGNOSTICS_TTL_MS: '1000' });
log.readCompleted('getNodes', timing);
assert.deepEqual(log.read().entries[0].affectedNodeIds, []);
const result = { operationId, ...scope, status: 'partially_applied', steps: [], affectedNodeIds: ['1:2'], affectedResourceIds: ['S:abc,'], warnings: [secret], error: { code: 'FIGMA_API_ERROR', message: secret, recoveryAction: secret } };
log.operationCompleted('applyBatch', timing, result);
let recorded = log.read();
assert.equal(recorded.entries[1].status, 'partially_applied');
assert.deepEqual(recorded.entries[1].affectedNodeIds, ['1:2']);
assert.deepEqual(recorded.entries[1].affectedResourceIds, ['S:abc,']);
assert.equal(recorded.extended.at(-1).errorCode, 'FIGMA_API_ERROR');
assert.equal(JSON.stringify(recorded).includes(secret), false);
const count = recorded.entries.length;
for (const invalid of [{ ...result, sessionId: 'foreign' }, { ...result, connectionGeneration: 8 }, { ...result, operationId: '019a4a10-0000-7000-8000-000000000002' }]) log.operationCompleted('applyBatch', timing, invalid);
assert.equal(log.read().entries.length, count);
log.failed('getNodes', timing, secret);
assert.equal(log.read().extended.at(-1).errorCode, 'FIGMA_API_ERROR');
assert.equal(JSON.stringify(log.read()).includes(secret), false);
assert.doesNotThrow(() => log.operationCompleted('applyBatch', timing, new Proxy({}, { get() { throw new Error(secret); } })));
assert.doesNotThrow(() => log.readCompleted('getNodes', new Proxy({}, { get() { throw new Error(secret); } })));
assert.doesNotThrow(() => log.failed('getNodes', timing, new Proxy({}, { get() { throw new Error(secret); } })));
log.clear();
assert.deepEqual(log.read(), { entries: [], extended: [], extendedEnabled: false });
log.close(); log.readCompleted('getNodes', timing);
assert.deepEqual(log.read(), { entries: [], extended: [], extendedEnabled: false });
const invalid = createDiagnosticsSession({ sessionId: secret, connectionGeneration: 1 }, secret);
assert.doesNotThrow(() => invalid.failed('getNodes', timing, secret));
assert.deepEqual(invalid.read(), { entries: [], extended: [], extendedEnabled: false });
console.log('Diagnostics session: trusted scope, confirmed IDs, redacted errors and non-interference OK');
