import assert from 'node:assert/strict';
import { build } from 'esbuild';
const built = await build({ entryPoints: ['shared/operation-journal.ts'], bundle: true, format: 'esm', platform: 'node', write: false });
const { OperationJournal } = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString('base64')}`);
const now = Date.now();
const id = (at, tail = '000000000001') => {
  const hex = at.toString(16).padStart(12, '0');
  return `${hex.slice(0, 8)}-${hex.slice(8)}-7000-8000-${tail}`;
};
const first = id(now);
const payload = { command: 'applyBatch', params: { steps: [{ expected: { name: 'before' }, op: 'renamePage' }] } };
const journal = new OperationJournal({ dedupTtl: 1000, clockSkew: 10, maxJournalEntries: 1 });
assert.equal(journal.reserve(first, payload, now).fresh, true);
assert.equal(journal.reserve(first, { params: payload.params, command: payload.command }, now).fresh, false);
journal.update(first, 'running');
assert.equal(journal.reserve(first, payload, now).status, 'running');
assert.throws(() => journal.reserve(first, { ...payload, params: {} }, now), /OPERATION_ID_CONFLICT/);
assert.throws(() => journal.reserve(id(now, '000000000002'), payload, now), /RESOURCE_LIMIT/);
assert.throws(() => journal.reserve(id(now + 11), payload, now), /INVALID_ARGUMENT/);
assert.throws(() => journal.reserve('arbitrary', payload, now), /INVALID_ARGUMENT/);
assert.throws(() => journal.update(first, 'queued'), /INVALID_ARGUMENT/);
assert.equal(journal.get(id(now, '000000000003')).status, 'unknown');
journal.update(first, 'unknown');
journal.update(first, 'succeeded', { affectedNodeIds: ['1:1'] });
assert.deepEqual(journal.reserve(first, payload, now).result, { affectedNodeIds: ['1:1'] });
assert.throws(() => journal.update(first, 'running'), /INVALID_ARGUMENT/);
assert.throws(() => journal.reserve(first, payload, now + 1011), /OPERATION_EXPIRED/);
assert.equal(journal.reserve(id(now + 1011), payload, now + 1011).fresh, true);
assert.throws(() => journal.reserve(first, payload, now + 1011), /OPERATION_EXPIRED/);
console.log('Журнал: повторы, конфликт payload, TTL, заполнение и неизвестный исход — OK');
