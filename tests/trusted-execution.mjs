import assert from 'node:assert/strict';
import { build } from 'esbuild';
const built = await build({ entryPoints: ['plugin/trusted-execution.ts', 'shared/execution-queue.ts', 'shared/operation-journal.ts', 'shared/batch-executor.ts', 'shared/execution-json.ts'], bundle: true, format: 'esm', platform: 'node', outdir: 'out', write: false });
const load = async n => import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[n].text).toString('base64')}`);
const { TrustedExecution } = await load(0), { ExecutionQueue } = await load(1), { OperationJournal } = await load(2), { BatchExecutor } = await load(3), { executionJson } = await load(4);
const now = Date.now();
const id = n => `${now.toString(16).padStart(12, '0').slice(0,8)}-${now.toString(16).padStart(12, '0').slice(8)}-7000-8000-${String(n).padStart(12,'0')}`;
const scope = { sessionId: 's', connectionGeneration: 1 }, queue = new ExecutionQueue(4);
const journal = new OperationJournal({ dedupTtl: 60000, clockSkew: 5000, maxJournalEntries: 20 });
let release, writes = [], undo = 0;
const wait = new Promise(resolve => { release = resolve; });
const api = { wait, writes };
const trusted = new TrustedExecution(journal, queue, { figma: api, checkScope() {}, yieldControl: async () => {}, commitUndo() { undo++; } }, 4, 30000);
const batch = new BatchExecutor(journal, { checkScope() {}, async prepare() {}, async readExpected() { return {}; }, async execute() { writes.push('batch'); return {}; }, commitUndo() {} }, 4, queue);
const input = { language: 'javascript', code: 'source', compiledCode: "figma.writes.push('start'); await figma.wait; figma.writes.push('end'); return { ok: true };" };
const first = trusted.submit(scope, id(1), input, now);
await Promise.resolve();
const second = batch.submit(scope, id(2), [{ stepId: 'x', op: 'createNode', type: 'FRAME', parent: { nodeId: '1:1' }, properties: {} }], now);
assert.deepEqual(writes, ['start']);
assert.equal((await trusted.submit(scope, id(1), input, now)).status, 'running');
assert.throws(() => trusted.submit(scope, id(1), { ...input, code: 'different' }, now), /OPERATION_ID_CONFLICT/);
assert.throws(() => batch.submit(scope, id(1), [{ stepId: 'x', op: 'createNode', type: 'FRAME', parent: { nodeId: '1:1' }, properties: {} }], now), /OPERATION_ID_CONFLICT/);
release();
assert.equal((await first).effects, 'unknown');
await second;
assert.deepEqual(writes, ['start', 'end', 'batch']);
assert.equal(undo, 1);
const bad = await trusted.submit(scope, id(3), { language: 'javascript', code: 'cycle', compiledCode: 'const x = {}; x.x = x; return x;' }, now);
assert.equal(bad.error.code, 'RESULT_NOT_SERIALIZABLE');
assert.equal(bad.error.phase, 'serialize');
assert.equal(bad.effects, 'unknown');
assert.throws(() => executionJson({ get x() { return 1; } }), /RESULT_NOT_SERIALIZABLE/);
assert.throws(() => executionJson(1n), /RESULT_NOT_SERIALIZABLE/);
assert.throws(() => executionJson(Object.fromEntries(Array.from({ length: 10001 }, (_, i) => [String(i), null]))), /RESULT_NOT_SERIALIZABLE/);
assert.throws(() => executionJson('a'.repeat(262145)), /RESOURCE_LIMIT/);
assert.equal(executionJson(undefined).json, 'null');
