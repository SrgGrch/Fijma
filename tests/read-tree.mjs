import assert from 'node:assert/strict';
import { build } from 'esbuild';
const built = await build({ entryPoints: ['shared/read-tree.ts'], bundle: true, format: 'esm', platform: 'node', write: false });
const { readTree } = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString('base64')}`);
const limits = { maxDepth: 8, maxNodes: 1000, maxResponseBytes: 262144, chunkSize: 50 };
const root = { id: 'root', name: '汉字 😀', type: 'FRAME', children: Array.from({ length: 5000 }, (_, i) => ({ id: String(i), name: `层 ${i}`, type: 'RECTANGLE' })) };
let yields = 0;
const result = await readTree(root, limits, { yieldControl: async () => { yields++; } });
assert.equal(result.nodes.length, 1000);
assert.equal(result.truncated, true);
assert.equal(result.bytes, Buffer.byteLength(JSON.stringify(result.nodes)));
assert.equal(yields, 20);
assert.deepEqual(result.nodes.slice(0, 3).map(row => row.nodeId), ['root', '0', '1']);
const shallow = await readTree(root, { ...limits, maxDepth: 0 });
assert.equal(shallow.nodes.length, 1);
assert.equal(shallow.truncated, true);
const rowBytes = Buffer.byteLength(JSON.stringify(shallow.nodes));
assert.equal((await readTree(root, { ...limits, maxResponseBytes: rowBytes })).nodes.length, 1);
assert.equal((await readTree(root, { ...limits, maxResponseBytes: rowBytes - 1 })).nodes.length, 0);
let stopped = false;
const cancelled = await readTree(root, limits, { stopped: () => stopped, yieldControl: async () => { stopped = true; } });
assert.equal(cancelled.nodes.length, 50);
assert.equal(cancelled.cancelled, true);
assert.equal(cancelled.truncated, true);
const otherPage = { get children() { throw new Error('Other page loaded'); } };
await readTree({ ...root, parent: otherPage }, limits);
await assert.rejects(readTree(root, { ...limits, maxNodes: 0 }), /INVALID_ARGUMENT/);
await assert.rejects(readTree(root, { ...limits, maxResponseBytes: 1 }), /INVALID_ARGUMENT/);
console.log('Ограниченное дерево: порядок, UTF-8, depth/node/byte границы, stop и изоляция области — OK');
