import assert from 'node:assert/strict';
import { build } from 'esbuild';
const built = await build({ entryPoints: ['plugin/export.ts'], bundle: true, format: 'esm', platform: 'node', write: false });
const { exportNode } = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString('base64')}`);
const png = (width, height, length = 33) => {
  const bytes = Buffer.alloc(length); Buffer.from([137, 80, 78, 71, 13, 10, 26, 10, 0, 0, 0, 13, 73, 72, 68, 82]).copy(bytes);
  bytes.writeUInt32BE(width, 16); bytes.writeUInt32BE(height, 20); return bytes;
};
let bytes = png(20, 10, 30000), exports = 0, yields = 0, settings;
const node = { id: 'n', type: 'FRAME', absoluteRenderBounds: { width: 10, height: 5 }, async exportAsync(value) { exports++; settings = value; return bytes; } };
const api = { getNodeByIdAsync: async id => id === 'n' ? node : null, base64Encode: data => Buffer.from(data).toString('base64') };
const limits = { maxExportPixels: 1000, maxExportBytes: 40000 };
let messages = [];
const run = (query, changed = limits, check = () => {}) => exportNode(api, query, changed, check, 12288, value => messages.push(value), async () => { yields++; });
await run({ nodeId: 'n', format: 'PNG', scale: 2 });
assert.equal(settings.constraint.value, 2);
assert.equal(messages[0].bytes, 30000);
assert.deepEqual([messages[0].width, messages[0].height, messages[0].total], [20, 10, 3]);
assert.deepEqual(Buffer.concat(messages.slice(1).map(value => Buffer.from(value.data, 'base64'))), bytes);
assert.equal(yields, 2);
messages = [];
await assert.rejects(run({ nodeId: 'n', format: 'SVG', scale: 2 }), /INVALID_ARGUMENT/);
await assert.rejects(run({ nodeId: 'missing', format: 'PNG' }), /NODE_NOT_FOUND/);
await assert.rejects(run({ nodeId: 'n', format: 'PNG', scale: 100 }), /RESOURCE_LIMIT/);
assert.equal(exports, 1);
bytes = png(101, 10);
await assert.rejects(run({ nodeId: 'n', format: 'PNG' }), /RESOURCE_LIMIT/);
bytes = Buffer.from('not a png');
await assert.rejects(run({ nodeId: 'n', format: 'PNG' }), /FIGMA_API_ERROR/);
bytes = Buffer.from('<svg/>');
await run({ nodeId: 'n', format: 'SVG' });
assert.deepEqual(settings, { format: 'SVG' });
assert.equal(messages[0].format, 'SVG');
assert.equal(Buffer.from(messages[1].data, 'base64').toString(), '<svg/>');
messages = [];
await assert.rejects(run({ nodeId: 'n', format: 'SVG' }, { ...limits, maxExportBytes: 2 }), /RESOURCE_LIMIT/);
assert.deepEqual(messages, []);
console.log('Export plugin: scale, bounds, actual PNG dimensions, chunking and size limits OK');
