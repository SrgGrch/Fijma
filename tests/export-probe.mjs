import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
const messages = [];
const figma = { showUI() {}, ui: { postMessage: value => messages.push(value) }, currentPage: { selection: [] } };
runInNewContext(await readFile('experiments/export-probe/main.js', 'utf8'), { figma, __html__: '' });
await figma.ui.onmessage({ type: 'export' });
assert.equal(messages.pop().type, 'error');
figma.currentPage.selection = [{ exportAsync: async ({ format }) => format === 'PNG' ? new Uint8Array([1, 2]) : '<svg/>' }];
await figma.ui.onmessage({ type: 'export' });
const exported = messages.pop();
assert.equal(exported.type, 'export');
assert.equal(exported.svg, '<svg/>');
assert.deepEqual([...exported.png], [1, 2]);
console.log('Диагностический экспорт: OK');
