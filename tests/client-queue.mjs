import assert from 'node:assert/strict';
import { build } from 'esbuild';
await build({ entryPoints: ['server/client-queue.ts'], bundle: true, platform: 'node', format: 'esm', outfile: 'dist/test-support/client-queue.mjs' });
const { ClientQueue } = await import('../dist/test-support/client-queue.mjs');
const deferred = () => { let resolve; const promise = new Promise(r => { resolve = r; }); return { promise, resolve }; };
const signal = () => new AbortController().signal;
let recovery = false;
const queue = new ClientQueue(() => recovery ? 'RECOVERY_REQUIRED' : undefined);
const held = deferred(), started = deferred(), order = [];
const first = queue.run(signal(), async () => { order.push(1); started.resolve(); await held.promise; }, 2, 1000);
await started.promise;
const second = queue.run(signal(), async () => { order.push(2); }, 2, 1000);
const third = queue.run(signal(), async () => { order.push(3); }, 2, 1000);
await assert.rejects(queue.run(signal(), async () => assert.fail('overflow ran'), 2, 1000), /RESOURCE_LIMIT/);
assert.deepEqual(order, [1]); held.resolve(); await Promise.all([first, second, third]); assert.deepEqual(order, [1, 2, 3]);

const blocked = deferred(), begun = deferred();
const active = queue.run(signal(), async () => { begun.resolve(); await blocked.promise; }, 3, 1000);
await begun.promise;
const client = new AbortController();
const aborted = assert.rejects(queue.run(client.signal, async () => assert.fail('disconnected job ran'), 3, 1000), /CANCELLED/);
client.abort(); await aborted;
await assert.rejects(queue.run(signal(), async () => assert.fail('expired job ran'), 3, 10), /QUEUE_TIMEOUT/);
const waiting = assert.rejects(queue.run(signal(), async () => assert.fail('uncertain write overlapped'), 3, 1000), /RECOVERY_REQUIRED/);
recovery = true; blocked.resolve(); await active; await waiting;
await assert.rejects(queue.run(signal(), async () => assert.fail('unsafe job ran'), 3, 1000), /RECOVERY_REQUIRED/);
recovery = false;
await queue.run(signal(), async () => order.push(4), 3, 1000);
assert.deepEqual(order, [1, 2, 3, 4]);
console.log('Client queue: FIFO, bounded backlog/wait, disconnect removal, recovery barrier and resume OK');
