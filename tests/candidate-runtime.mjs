import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
const source = await readFile('dist/candidate/main.js', 'utf8');
const messages = [], nodes = new Map();
let count = 0, undos = 0, holdYield = false, waiting, holdRead = false, releaseRead;
const figma = { root: { name: 'Document', children: [] }, currentPage: { id: 'page', selection: [] },
  showUI() {}, ui: { postMessage: m => { if (m.type === 'yield') { if (holdYield) waiting = m; else setImmediate(() => figma.ui.onmessage(m)); } else messages.push(m); } },
  createPage() { const page = { id: `page:${++count}`, type: 'PAGE', name: '' }; nodes.set(page.id, page); return page; },
  async getNodeByIdAsync(id) { if (holdRead) await new Promise(resolve => { releaseRead = resolve; }); return nodes.get(id) ?? null; }, commitUndo() { undos++; } };
runInNewContext(source, { figma, __html__: '', setTimeout, clearTimeout });
await figma.ui.onmessage({ type: 'hello-request' });
const hello = messages.pop();
await figma.ui.onmessage({ ...hello, type: 'welcome', connectionGeneration: 1 }); messages.pop();
const timestamp = Date.now().toString(16).padStart(12, '0');
const operationId = `${timestamp.slice(0,8)}-${timestamp.slice(8)}-7000-8000-000000000001`;
const cmd = { type: 'command', sessionId: hello.sessionId, connectionGeneration: 1, operationId, command: 'applyBatch', params: { steps: [{ stepId: 'page', op: 'createPage', name: 'Created' }] } };
await figma.ui.onmessage(cmd);
assert.equal(messages.pop().data.error.code, 'WRITE_DISABLED');
await figma.ui.onmessage({ type: 'setWriteEnabled', enabled: true });
assert.equal(messages.pop().enabled, true);
await figma.ui.onmessage(cmd);
const result = messages.pop().data;
assert.equal(result.status, 'succeeded');
assert.equal(result.steps[0].appliedChanges.details[0].properties.name, 'Created');
assert.equal(count, 1); assert.equal(undos, 1);
await figma.ui.onmessage(cmd);
assert.equal(messages.pop().data.status, 'succeeded'); assert.equal(count, 1);
await figma.ui.onmessage({ type: 'stop' }); messages.pop();
await figma.ui.onmessage({ ...cmd, operationId: operationId.replace(/1$/, '2') });
assert.equal(messages.pop().data.error.code, 'WRITE_DISABLED');
await figma.ui.onmessage({ type: 'setWriteEnabled', enabled: true }); messages.pop();
const unsupported = { ...cmd, operationId: operationId.replace(/1$/, '3'), params: { steps: [cmd.params.steps[0], { stepId: 'unsupported', op: 'createCollection', name: 'X' }] } };
await figma.ui.onmessage(unsupported);
assert.equal(messages.pop().data.error.code, 'CAPABILITY_UNAVAILABLE'); assert.equal(count, 1);
const unsupportedField = { ...cmd, operationId: operationId.replace(/1$/, '7'), params: { steps: [cmd.params.steps[0], { stepId: 'frame', op: 'createNode', type: 'FRAME', parent: { nodeId: 'page' }, properties: { opacity: 0.5 } }] } };
await figma.ui.onmessage(unsupportedField);
assert.equal(messages.pop().data.error.code, 'CAPABILITY_UNAVAILABLE'); assert.equal(count, 1);
holdYield = true;
const pending = figma.ui.onmessage({ ...cmd, operationId: operationId.replace(/1$/, '4'), params: { steps: [cmd.params.steps[0], { ...cmd.params.steps[0], stepId: 'next' }] } });
await new Promise(resolve => setImmediate(resolve));
assert.ok(waiting);
await figma.ui.onmessage({ type: 'stop' }); messages.pop();
figma.ui.onmessage(waiting); await pending;
assert.equal(messages.pop().data.status, 'cancelled'); assert.equal(count, 1);
await figma.ui.onmessage({ type: 'setWriteEnabled', enabled: true }); messages.pop();
holdYield = false;
await figma.ui.onmessage({ ...cmd, operationId: operationId.replace(/1$/, '6'), params: { steps: [{ ...cmd.params.steps[0], name: 'x'.repeat(5000) }] } });
const oversized = messages.pop().data;
assert.equal(oversized.status, 'partially_applied'); assert.equal(oversized.error.code, 'RESOURCE_LIMIT');
assert.equal(oversized.affectedNodeIds.length, 1); assert.ok(!oversized.steps[0].appliedChanges.details);
holdRead = true;
const changedDocument = figma.ui.onmessage({ ...cmd, operationId: operationId.replace(/1$/, '5') });
for (let i = 0; i < 20 && !releaseRead; i++) await new Promise(resolve => setImmediate(resolve));
assert.ok(releaseRead); figma.root = { name: 'Another document', children: [] }; releaseRead();
await changedDocument;
const changedResult = messages.pop().data;
assert.equal(changedResult.status, 'partially_applied');
assert.equal(changedResult.error.code, 'DOCUMENT_MISMATCH');
assert.equal(changedResult.affectedNodeIds.length, 1); assert.equal(undos, 2);
console.log('Candidate fakeFigma: gated writes, readback, dedup, stop OK');
