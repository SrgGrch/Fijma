import assert from 'node:assert/strict';
import { build } from 'esbuild';
const built = await build({ entryPoints: ['plugin/layout-ops.ts', 'shared/batch-executor.ts', 'shared/operation-journal.ts'], outdir: 'out', bundle: true, format: 'esm', platform: 'node', write: false });
const load = async n => import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[n].text).toString('base64')}`);
const { layoutOperations } = await load(0), { BatchExecutor } = await load(1), { OperationJournal } = await load(2);
const parent = { id: 'p', type: 'FRAME', layoutMode: 'NONE' };
const node = { id: 'n', type: 'FRAME', name: 'Frame', parent, layoutPositioning: 'AUTO',
  constraints: { horizontal: 'MIN', vertical: 'MIN' }, layoutMode: 'NONE', layoutWrap: 'NO_WRAP',
  paddingTop: 1, paddingRight: 2, paddingBottom: 3, paddingLeft: 4, itemSpacing: 5, counterAxisSpacing: 6,
  primaryAxisAlignItems: 'MIN', counterAxisAlignItems: 'MIN', layoutSizingHorizontal: 'FIXED', layoutSizingVertical: 'FIXED', boundVariables: {} };
const api = { getNodeByIdAsync: async id => id === node.id ? node : id === parent.id ? parent : null };
const ops = layoutOperations(api);
const executor = new BatchExecutor(new OperationJournal({ dedupTtl: 10000, clockSkew: 100, maxJournalEntries: 30 }), { ...ops, checkScope() {}, commitUndo() {} }, 10);
const now = Date.now(), hex = now.toString(16).padStart(12, '0');
const id = n => `${hex.slice(0, 8)}-${hex.slice(8)}-7000-8000-${String(n).padStart(12, '0')}`;
const scope = { sessionId: 's', connectionGeneration: 1 };
const run = (n, step) => executor.submit(scope, id(n), [{ stepId: 'layout', target: { nodeId: 'n' }, expected: { name: 'Frame' }, ...step }], now);
const constraints = await run(1, { op: 'setConstraints', value: { horizontal: 'MAX', vertical: 'STRETCH' } });
assert.equal(constraints.status, 'succeeded');
assert.deepEqual(node.constraints, { horizontal: 'MAX', vertical: 'STRETCH' });
const layout = await run(2, { op: 'setAutoLayout', layout: { layoutMode: 'HORIZONTAL', layoutWrap: 'WRAP', paddingLeft: 12, counterAxisSpacing: 8 } });
assert.equal(layout.status, 'succeeded');
assert.deepEqual([node.layoutMode, node.layoutWrap, node.paddingLeft, node.counterAxisSpacing], ['HORIZONTAL', 'WRAP', 12, 8]);
assert.deepEqual([node.paddingTop, node.paddingRight, node.paddingBottom, node.itemSpacing], [1, 2, 3, 5]);
parent.layoutMode = 'HORIZONTAL';
assert.equal((await run(13, { op: 'setConstraints', value: { horizontal: 'MIN', vertical: 'MIN' } })).error.code, 'CAPABILITY_UNAVAILABLE');
assert.deepEqual(node.constraints, { horizontal: 'MAX', vertical: 'STRETCH' });
const size = await run(3, { op: 'setLayoutSizing', sizing: { horizontal: 'FILL', vertical: 'HUG' } });
assert.equal(size.status, 'succeeded');
assert.deepEqual([node.layoutSizingHorizontal, node.layoutSizingVertical], ['FILL', 'HUG']);
node.boundVariables = { opacity: { type: 'VARIABLE_ALIAS', id: 'untouched' } };
assert.equal((await run(4, { op: 'setAutoLayout', layout: { paddingTop: 9 } })).status, 'succeeded');
assert.equal(node.boundVariables.opacity.id, 'untouched');
assert.equal((await run(5, { op: 'setAutoLayout', layout: { layoutMode: 'VERTICAL' } })).error.code, 'CAPABILITY_UNAVAILABLE');
node.boundVariables = { paddingRight: { type: 'VARIABLE_ALIAS', id: 'v' } };
assert.equal((await run(6, { op: 'setAutoLayout', layout: { paddingRight: 10 } })).error.code, 'CAPABILITY_UNAVAILABLE');
assert.equal(node.paddingRight, 2);
node.boundVariables = {};
assert.equal((await run(7, { op: 'setAutoLayout', layout: { layoutWrap: 'NO_WRAP', counterAxisSpacing: 5 } })).error.code, 'INVALID_ARGUMENT');
assert.equal(node.layoutWrap, 'WRAP');
assert.equal((await run(12, { op: 'setAutoLayout', layout: { layoutMode: 'VERTICAL', counterAxisAlignItems: 'BASELINE' } })).error.code, 'INVALID_ARGUMENT');
assert.equal(node.layoutMode, 'HORIZONTAL');
parent.layoutMode = 'NONE';
assert.equal((await run(8, { op: 'setLayoutSizing', sizing: { horizontal: 'FILL', vertical: 'FIXED' } })).error.code, 'INVALID_ARGUMENT');
assert.equal(node.layoutSizingHorizontal, 'FILL');
parent.layoutMode = 'HORIZONTAL';
node.layoutPositioning = 'ABSOLUTE';
assert.equal((await run(9, { op: 'setLayoutSizing', sizing: { horizontal: 'FILL', vertical: 'FIXED' } })).error.code, 'INVALID_ARGUMENT');
node.layoutPositioning = 'AUTO';
node.layoutMode = 'NONE';
assert.equal((await run(10, { op: 'setLayoutSizing', sizing: { horizontal: 'HUG', vertical: 'FIXED' } })).error.code, 'INVALID_ARGUMENT');
node.layoutMode = 'HORIZONTAL';
Object.defineProperty(node, 'paddingBottom', { get() { return 3; }, set() { throw new Error('write failed'); }, configurable: true });
const partial = await run(11, { op: 'setAutoLayout', layout: { paddingTop: 15, paddingBottom: 16 } });
assert.equal(partial.status, 'partially_applied');
assert.deepEqual(partial.affectedNodeIds, ['n']);
assert.equal(node.paddingTop, 15);
await assert.rejects(ops.prepare({ stepId: 'x', op: 'setAutoLayout', target: { nodeId: 'n' }, expected: { name: 'Frame' }, layout: { unsupported: 1 } }), /INVALID_ARGUMENT/);
console.log('Layout callbacks: constraints, wrap, sizing, bindings, preflight and partial failures OK');
