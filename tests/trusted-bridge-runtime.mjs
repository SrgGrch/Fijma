import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
const source = await readFile('dist/plugin/main.js', 'utf8');
const messages = [], events = [];
let release;
const wait = new Promise(resolve => { release = resolve; });
const figma = { root: { name: 'Bound', children: [] }, currentPage: { id: 'page', selection: [] }, wait, events,
  showUI() {}, ui: { postMessage(m) { if (m.type === 'yield') setImmediate(() => figma.ui.onmessage(m)); else messages.push(m); } },
  createPage() { events.push('batch'); return { id: 'p', type: 'PAGE', name: '' }; },
  async getNodeByIdAsync() { return null; }, commitUndo() {}, base64Encode(bytes) { return Buffer.from(bytes).toString('base64'); } };
runInNewContext(source, { figma, __html__: '', setTimeout, clearTimeout });
await figma.ui.onmessage({ type: 'hello-request' });
const hello = messages.pop();
await figma.ui.onmessage({ ...hello, type: 'welcome', connectionGeneration: 1 }); messages.length = 0;
const time = Date.now().toString(16).padStart(12, '0');
const id = n => `${time.slice(0, 8)}-${time.slice(8)}-7000-8000-${String(n).padStart(12, '0')}`;
const cmd = (n, command, params) => ({ type: 'command', sessionId: hello.sessionId, connectionGeneration: 1, operationId: id(n), requestId: `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`, command, params });
const execute = cmd(1, 'execute', { language: 'javascript', code: 'await figma.wait; return 1;', compiledCode: "figma.events.push('start'); await figma.wait; figma.events.push('end'); return 1;" });
await figma.ui.onmessage(execute);
assert.equal(messages.pop().data.error.code, 'EXECUTION_DISABLED');
await figma.ui.onmessage({ type: 'setExecuteEnabled', enabled: true });
assert.equal(messages.pop().enabled, true);
const running = figma.ui.onmessage(execute);
await new Promise(resolve => setImmediate(resolve));
assert.deepEqual(events, ['start']);
await figma.ui.onmessage(cmd(3, 'getNodes', { nodeIds: ['p'], fields: ['name'] }));
assert.equal(messages.pop().code, 'RESOURCE_LIMIT');
await figma.ui.onmessage({ type: 'setWriteEnabled', enabled: true }); messages.pop();
const batch = figma.ui.onmessage(cmd(2, 'applyBatch', { steps: [{ stepId: 'page', op: 'createPage', name: 'Created' }] }));
await new Promise(resolve => setImmediate(resolve));
assert.deepEqual(events, ['start']);
await figma.ui.onmessage({ type: 'setWriteEnabled', enabled: false }); messages.pop();
release(); await Promise.all([running, batch]);
assert.deepEqual(events, ['start', 'end']);
assert.equal(messages.find(m => m.operationId === id(1)).data.effects, 'unknown');
assert.equal(messages.find(m => m.operationId === id(2)).data.status, 'cancelled');
messages.length = 0;
await figma.ui.onmessage({ type: 'stop' });
await figma.ui.onmessage(cmd(4, 'execute', { ...execute.params, code: 'return 1;', compiledCode: 'return 1;' }));
assert.equal(messages.pop().data.error.code, 'EXECUTION_DISABLED');
await figma.ui.onmessage({ type: 'setExecuteEnabled', enabled: true }); messages.pop();
const large = cmd(5, 'execute', { language: 'javascript', code: 'return "x".repeat(40000);', compiledCode: 'return "x".repeat(40000);' });
await figma.ui.onmessage(large);
const start = messages.find(m => m.type === 'executionStart');
const chunks = messages.filter(m => m.type === 'executionChunk');
assert.equal(start.requestId, large.requestId);
assert.equal(chunks.length, start.total);
assert.equal(Buffer.concat(chunks.map(c => Buffer.from(c.data, 'base64'))).length, start.bytes);
assert.equal(messages.find(m => m.type === 'operationResult' && m.operationId === id(5)).data.valueResourcePending, true);
await figma.ui.onmessage({ type: 'disconnected' });
await figma.ui.onmessage({ type: 'hello-request' });
const next = messages.pop();
await figma.ui.onmessage({ ...next, type: 'welcome', connectionGeneration: 2 }); messages.pop();
await figma.ui.onmessage({ ...cmd(6, 'execute', { ...large.params }), connectionGeneration: 2 });
assert.equal(messages.pop().data.error.code, 'EXECUTION_DISABLED');
