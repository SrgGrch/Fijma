import assert from 'node:assert/strict';
import { build } from 'esbuild';
const built = await build({ entryPoints: ['server/diagnostics.ts'], bundle: true, format: 'esm', platform: 'node', write: false });
const { createDiagnostics } = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString('base64')}`);
const secret = 'a'.repeat(64), text = 'private design text', image = 'private image bytes';
const binding = { sessionId: 'bound-session', connectionGeneration: 7 };
const log = createDiagnostics(binding, secret, { maxEntries: 2, maxExtendedTtlMs: 100 });
const operationId = '019a4a10-0000-7000-8000-000000000001';
const metadata = { operationId, action: 'applyBatch', durationMs: 5, status: 'succeeded', affectedNodeIds: ['1:2'], affectedResourceIds: ['VariableID:1:2', 'S:abcdef123456,'], characters: text, image, secret, sessionId: 'forged' };
const detail = { errorCode: 'CONFLICT', stepCount: 1, queueDepth: 2, secret, message: text, payload: { image } };
log.record(metadata, detail);
let result = log.read();
assert.equal(result.entries[0].sessionId, 'bound-session');
assert.deepEqual(result.entries[0].affectedResourceIds, ['VariableID:1:2', 'S:abcdef123456,']);
assert.deepEqual(result.extended, []);
for (const privateValue of [secret, text, image, 'forged']) assert.equal(JSON.stringify(result).includes(privateValue), false);
log.enableExtended(50);
log.record(metadata, detail);
result = log.read();
assert.equal(result.extendedEnabled, true);
assert.deepEqual(result.extended[0], { operationId, connectionGeneration: 7, errorCode: 'CONFLICT', stepCount: 1, queueDepth: 2 });
for (const privateValue of [secret, text, image, 'forged']) assert.equal(JSON.stringify(result).includes(privateValue), false);
result.entries[0].affectedNodeIds.push('modified');
assert.deepEqual(log.read().entries[0].affectedNodeIds, ['1:2']);
log.record(metadata, detail);
assert.equal(log.read().entries.length, 2);
assert.equal(log.read().extended.length, 2);
for (const bad of [{ ...metadata, action: text }, { ...metadata, status: secret }, { ...metadata, affectedNodeIds: [secret] }, { ...metadata, affectedResourceIds: [`VariableID:${secret}`] }, { ...metadata, affectedResourceIds: ['S:foo, payload'] }]) {
  assert.throws(() => log.record(bad), error => error.message === 'INVALID_ARGUMENT' && !String(error).includes(secret) && !String(error).includes(text));
}
assert.throws(() => log.record(metadata, { errorCode: secret }), /^Error: INVALID_ARGUMENT$/);
assert.throws(() => log.enableExtended(101), /^Error: INVALID_ARGUMENT$/);
await new Promise(resolve => setTimeout(resolve, 80));
assert.equal(log.read().extendedEnabled, false);
assert.deepEqual(log.read().extended, []);
assert.equal(log.read().entries.length, 2);
log.enableExtended(50); log.record(metadata, detail); log.clear();
assert.deepEqual(log.read(), { entries: [], extended: [], extendedEnabled: false });
assert.throws(() => createDiagnostics({ ...binding, sessionId: secret }, secret), /^Error: INVALID_ARGUMENT$/);
console.log('Diagnostics metadata: allowlist, binding, redaction, opt-in TTL, bounds and clear OK');
