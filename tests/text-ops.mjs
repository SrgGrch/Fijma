import assert from 'node:assert/strict';
import { build } from 'esbuild';
const built = await build({ entryPoints: ['plugin/text-ops.ts', 'shared/batch-executor.ts', 'shared/operation-journal.ts'], outdir: 'out', bundle: true, format: 'esm', platform: 'node', write: false });
const load = async n => import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[n].text).toString('base64')}`);
const { textOperations } = await load(0), { BatchExecutor } = await load(1), { OperationJournal } = await load(2);
const now = Date.now(), hex = now.toString(16).padStart(12, '0');
const id = n => `${hex.slice(0,8)}-${hex.slice(8)}-7000-8000-${String(n).padStart(12,'0')}`;
const inter = { family: 'Inter', style: 'Regular' }, bold = { family: 'Inter', style: 'Bold' }, serif = { family: 'Serif', style: 'Regular' };
let loaded = [], nodes = new Map(), serial = 0, loadHook;
const parent = { id: 'p', type: 'FRAME', children: [], appendChild(child) { child.parent = this; this.children.push(child); } };
nodes.set(parent.id, parent);
function textNode(fonts = [inter], text = 'Hello') {
  const n = { id: `text:${++serial}`, type: 'TEXT', name: 'Text', characters: text, fontName: fonts.length === 1 ? fonts[0] : Symbol('mixed'), fonts, textStyleId: '', boundVariables: {}, fontSize: 12, hasMissingFont: false,
    getRangeAllFontNames() { return this.fonts; },
    getStyledTextSegments() { return this.fonts.map(fontName => ({ fontName, textStyleId: this.textStyleId, boundVariables: this.boundVariables })); },
  };
  nodes.set(n.id, n); return n;
}
const api = { async getNodeByIdAsync(id) { return nodes.get(id); }, async loadFontAsync(font) { loaded.push(font); if (loadHook) await loadHook(font); if (font.family === 'Missing') throw Error('font missing'); }, createText() { return textNode([inter], ''); } };
const handler = textOperations(api);
const executor = new BatchExecutor(new OperationJournal({ dedupTtl: 10000, clockSkew: 10, maxJournalEntries: 30 }), { ...handler, checkScope() {}, commitUndo() {} }, 10);
const scope = { sessionId: 's', connectionGeneration: 1 };
const run = (n, step) => executor.submit(scope, id(n), [step], now);
const create = (font, typography = {}) => ({ stepId: 'create', op: 'createText', parent: { nodeId: 'p' }, characters: 'new', font, typography });
const update = (node, patch, expected = { characters: node.characters }) => ({ stepId: 'update', op: 'updateNode', type: 'TEXT', target: { nodeId: node.id }, patch, expected });
const created = await run(1, create(inter, { fontSize: 16, textAlignHorizontal: 'CENTER' }));
assert.equal(created.status, 'succeeded');
const createdNode = nodes.get(created.steps[0].outputs.nodeId);
assert.equal(createdNode.characters, 'new'); assert.equal(createdNode.fontSize, 16); assert.equal(createdNode.parent, parent);
assert.deepEqual(loaded, [inter]);
loaded = [];
const mixed = textNode([inter, bold]);
const changed = await run(2, update(mixed, { fontName: serif, fontSize: 18 }));
assert.equal(changed.status, 'succeeded');
assert.deepEqual(loaded, [inter, bold, serif]);
assert.equal(mixed.fontSize, 18); assert.deepEqual(mixed.fontName, serif);
loaded = [];
const unavailable = textNode([inter, { family: 'Missing', style: 'Regular' }]);
const failed = await run(3, update(unavailable, { fontSize: 32 }));
assert.equal(failed.error.code, 'FONT_UNAVAILABLE'); assert.equal(unavailable.fontSize, 12); assert.deepEqual(failed.affectedNodeIds, []);
assert.deepEqual(failed.error.details, { fonts: [{ family: 'Missing', style: 'Regular' }] });
assert.deepEqual(failed.steps[0].error.details, failed.error.details);
const several = textNode([{ family: 'Missing', style: 'Regular' }, { family: 'Missing', style: 'Bold' }]);
several.hasMissingFont = true;
const severalFailed = await run(16, update(several, { fontSize: 32 }));
assert.deepEqual(severalFailed.error.details, { fonts: several.fonts });
assert.equal(several.fontSize, 12);
const count = nodes.size;
assert.equal((await run(4, create({ family: 'Missing', style: 'Regular' }))).error.code, 'FONT_UNAVAILABLE');
assert.equal(nodes.size, count);
const styled = textNode(); styled.textStyleId = 'style:1';
assert.equal((await run(5, update(styled, { fontSize: 20 }))).error.code, 'CAPABILITY_UNAVAILABLE'); assert.equal(styled.fontSize, 12);
const bound = textNode(); bound.getStyledTextSegments = () => [{ textStyleId: '', boundVariables: { fontSize: { id: 'variable' } } }];
assert.equal((await run(6, update(bound, { fontSize: 20 }))).error.code, 'CAPABILITY_UNAVAILABLE'); assert.equal(bound.fontSize, 12);
let release, signal;
const paused = new Promise(r => { release = r; }), started = new Promise(r => { signal = r; });
const race = textNode([inter]);
loadHook = async () => { signal(); await paused; };
const pending = run(7, update(race, { fontSize: 14 }));
await started; race.fonts = [bold]; release();
assert.equal((await pending).error.code, 'CONFLICT'); assert.equal(race.fontSize, 12);
loadHook = undefined;
const failure = textNode(); Object.defineProperty(failure, 'fontSize', { get() { return 12; }, set() { throw Error('bad'); } });
const partial = await run(8, update(failure, { fontName: serif, fontSize: 14 }));
assert.equal(partial.status, 'partially_applied'); assert.deepEqual(partial.affectedNodeIds, [failure.id]); assert.deepEqual(failure.fontName, serif);
console.log('Text callbacks: creation, mixed/missing fonts, bindings, races and partial errors OK');
const stale = textNode();
assert.equal((await run(9, update(stale, { fontSize: 30 }, { characters: 'old' }))).error.code, 'CONFLICT');
assert.equal(stale.fontSize, 12);
const wrong = await run(10, create(inter, { fontName: bold }));
assert.equal(wrong.error.code, 'INVALID_ARGUMENT');
const deletedDuringLoad = { id: 'gone', type: 'FRAME', appendChild() {} };
nodes.set('gone', deletedDuringLoad);
let releaseParent, startParent;
const parentWait = new Promise(r => { releaseParent = r; }), parentStart = new Promise(r => { startParent = r; });
loadHook = async () => { startParent(); await parentWait; };
const countBeforeParentRace = nodes.size;
const createRace = run(11, { ...create(inter), parent: { nodeId: 'gone' } });
await parentStart; deletedDuringLoad.removed = true; releaseParent();
assert.equal((await createRace).error.code, 'NODE_NOT_FOUND');
assert.equal(nodes.size, countBeforeParentRace);
loadHook = undefined;
const dispatcherBuild = await build({ entryPoints: ['plugin/write-operations.ts'], bundle: true, format: 'esm', platform: 'node', write: false });
const { writeOperations } = await import(`data:text/javascript;base64,${Buffer.from(dispatcherBuild.outputFiles[0].text).toString('base64')}`);
const dispatch = writeOperations(api);
const composed = new BatchExecutor(new OperationJournal({ dedupTtl: 10000, clockSkew: 10, maxJournalEntries: 30 }), { ...dispatch, checkScope() {}, commitUndo() {} }, 10);
const compose = (n, step) => composed.submit(scope, id(n), [step], now);
const beforeMissing = nodes.size;
const missing = { family: 'Missing', style: 'Regular' };
const dedicatedMissing = await compose(12, create(missing));
const genericMissing = await compose(13, { stepId: 'generic', op: 'createNode', type: 'TEXT', parent: { nodeId: 'p' }, properties: { fontName: missing, characters: 'new' } });
assert.equal(dedicatedMissing.error.code, 'FONT_UNAVAILABLE');
assert.equal(genericMissing.error.code, 'FONT_UNAVAILABLE');
assert.deepEqual(dedicatedMissing.error.details, { fonts: [missing] });
assert.deepEqual(genericMissing.error.details, { fonts: [missing] });
assert.equal(nodes.size, beforeMissing);
const generic = await compose(14, { stepId: 'generic', op: 'createNode', type: 'TEXT', parent: { nodeId: 'p' }, properties: { name: 'Caption', fontName: inter, characters: 'caption', fontSize: 22 } });
const genericNode = nodes.get(generic.steps[0].outputs.nodeId);
assert.equal(generic.status, 'succeeded'); assert.equal(genericNode.name, 'Caption'); assert.equal(genericNode.characters, 'caption'); assert.equal(genericNode.fontSize, 22);
const combined = await compose(15, update(genericNode, { name: 'Updated', fontSize: 24 }));
assert.equal(combined.status, 'succeeded'); assert.equal(genericNode.name, 'Updated'); assert.equal(genericNode.fontSize, 24);
