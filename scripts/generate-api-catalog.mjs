import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join } from 'node:path';

const root = process.env.FIGMA_TYPINGS_DIR || 'node_modules/@figma/plugin-typings';
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
if (pkg.version !== '1.142.0') throw new Error(`Expected typings 1.142.0, got ${pkg.version}`);
const source = await readFile(join(root, 'plugin-api.d.ts'), 'utf8');
const sourceSha256 = createHash('sha256').update(source).digest('hex');
if (sourceSha256 !== '46685808f4994664397367ff855ff87619f8177370da572f7d3acfd2553dc95a') throw new Error('Unreviewed typings source: update the generator after checking its syntax and declarations');
const lines = source.match(/[^\n]*\n|[^\n]+$/g) || [];
const declarations = new Map();
let name, headerCount = 0, prelude = '';
for (const line of lines) {
  const match = /^(?:declare )?(interface|type) ([A-Za-z_$][\w$]*)\b/.exec(line);
  if (match) {
    name = match[2]; headerCount++;
    declarations.set(name, (declarations.get(name) || '') + line);
  } else {
    // Top-level declarations in the pinned source must use a supported syntax.
    if (/^[^\s/*}>]/.test(line)) throw new Error(`Unsupported top-level syntax: ${line.slice(0, 100)}`);
    if (name) declarations.set(name, declarations.get(name) + line);
    else prelude += line;
  }
}
if (!headerCount || !/^\s*(?:\/\*[\s\S]*?\*\/\s*)*$/.test(prelude)) throw new Error('Unsupported declaration prelude');
// Preserve every declaration byte; comments before the first declaration belong to the first type.
const first = declarations.keys().next().value;
declarations.set(first, prelude + declarations.get(first));
if ([...declarations.values()].reduce((n, value) => n + value.length, 0) !== source.length) throw new Error('Declaration accounting failed');
const names = [...declarations.keys()].sort();
const chunk = (text) => {
  const pages = []; let current = '';
  for (const character of text) {
    if (Buffer.byteLength(JSON.stringify(current + character), 'utf8') > 12000) { pages.push(current); current = ''; }
    current += character;
  }
  if (current || !pages.length) pages.push(current);
  return pages;
};
const types = Object.fromEntries(names.map(n => {
  const text = declarations.get(n);
  const related = [...new Set(text.match(/\b[A-Z][A-Za-z0-9_$]*\b/g) || [])].filter(x => x !== n && declarations.has(x)).sort();
  return [n, { pages: chunk(text), related }];
}));
const indexPayload = names => ({ names: names.map(name => ({ name, uri: `figma-api://types/${name}/0` })) });
const size = value => Buffer.byteLength(JSON.stringify(value), 'utf8');
const indexPages = []; let page = [];
for (const n of names) {
  if (page.length && size(indexPayload([...page, n])) > 30000) { indexPages.push(page); page = []; }
  page.push(n);
}
if (page.length) indexPages.push(page);
const buildVersion = JSON.parse(await readFile('package.json', 'utf8')).version;
const data = { typingsVersion: pkg.version, buildVersion, sourceSha256, declarationCount: headerCount, indexPages, types };
// Check the serialized resources, including every URI and related-type link, before publishing.
for (const names of indexPages) if (size(indexPayload(names)) > 32768) throw new Error('Index page exceeds 32 KiB');
for (const [name, type] of Object.entries(types)) {
  for (const [page, signature] of type.pages.entries()) {
    const payload = { name, page, pages: type.pages.length, signature,
      related: type.related.map(name => `figma-api://types/${name}/0`), runtimeSupport: 'unknown' };
    if (size(payload) > 32768) throw new Error(`Type page exceeds 32 KiB: ${name}/${page}`);
  }
}
const indexMetadata = { typingsVersion: data.typingsVersion, buildVersion, sourceSha256, declarationCount: headerCount,
  runtimeSupport: 'unknown', notes: 'Declarations describe pinned typings, not runtime support (unknown). Dynamic-page may require page.loadAsync(); load fonts before editing text. Check figma.mixed and instance restrictions; variable bindings require compatible types. Yield cooperatively; Stop is not a hard interruption.',
  pages: indexPages.map((_, i) => `figma-api://index/${i}`) };
if (size(indexMetadata) > 32768) throw new Error('Index metadata exceeds 32 KiB');
await writeFile('server/api-catalog.generated.ts', `// Generated by scripts/generate-api-catalog.mjs; do not edit.\nexport const apiCatalog = ${JSON.stringify(data)} as const;\n`);
